import type { ReactNode } from "react";
import { Sparkles } from "lucide-react";
import { cn } from "@/lib/format";

// Shared look for everything the (simulated) assistant writes, so advisors can
// always tell generated guidance apart from account data.

/** "Assistant" mark with a Simulated pill — the assistant is rules, not a model. */
export function AssistantMark({
  className,
  label = "Assistant",
}: {
  className?: string;
  label?: string;
}) {
  return (
    <span
      className={cn(
        "inline-flex items-center gap-1.5 text-sm font-semibold text-pnc-blue-800",
        className,
      )}
    >
      <Sparkles className="size-4 text-pnc-blue-700" aria-hidden="true" />
      {label}
      <span
        title="Generated by rules from mock data. Not a language model."
        className="rounded-full bg-white px-1.5 py-px text-[10px] font-bold uppercase tracking-wide text-pnc-muted ring-1 ring-pnc-line"
      >
        Simulated
      </span>
    </span>
  );
}

/** Light blue panel that holds assistant output. */
export function AssistantPanel({
  title,
  aside,
  children,
  className,
}: {
  title?: ReactNode;
  aside?: ReactNode;
  children: ReactNode;
  className?: string;
}) {
  return (
    <section className={cn("rounded-md bg-pnc-blue-50 p-4 @3xl:p-5", className)}>
      <header className="mb-3 flex flex-wrap items-center justify-between gap-2">
        <div className="space-y-0.5">
          <AssistantMark />
          {title && <h3 className="font-display text-lg font-medium text-pnc-ink">{title}</h3>}
        </div>
        {aside}
      </header>
      {children}
    </section>
  );
}

