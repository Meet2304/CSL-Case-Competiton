/**
 * The account decision tree. Each decision node asks one question about one
 * fact and has a branch for every value that fact can take (a test enforces
 * this). Numbers are never branched on here: thresholds live in overlays and
 * household rules so the tree stays exhaustive.
 *
 * `summary` is the advisor's voice. `plain` is what the client would read:
 * gentle, no deadlines, no "must".
 */
