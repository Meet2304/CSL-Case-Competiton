/** Branches on account class: `routes` maps the classes that go somewhere specific. */
function byClass(
  routes: Partial<Record<AccountClass, string>>,
  otherwise: string,
): DecisionNode["branches"] {
  return (Object.keys(classLabels) as AccountClass[]).map((c) => ({
    when: c,
    label: classLabels[c],
    next: routes[c] ?? otherwise,
  }));
}

